-- Turns the keybinds.lua registry into real binds + the generated shortcuts views.

local safety = require("lib.safety")

local M = {}

local GROUP_ORDER = { "Apps", "Windows", "Workspaces", "Screenshots", "Session", "Media" }

local function normalize(keys)
    return (keys:gsub("%s+", " "):upper())
end

local function dispatcher(e)
    if e.exec then return hl.dsp.exec_cmd(e.exec) end
    if e.dsp then return e.dsp() end
    error("bind '" .. e.keys .. "' has neither exec nor dsp")
end

local function grouped(binds)
    local groups, order, seen = {}, {}, {}
    for _, g in ipairs(GROUP_ORDER) do order[#order + 1] = g; seen[g] = true end
    for _, e in ipairs(binds) do
        if not e.hidden then
            if not seen[e.group] then order[#order + 1] = e.group; seen[e.group] = true end
            groups[e.group] = groups[e.group] or {}
            table.insert(groups[e.group], e)
        end
    end
    return groups, order
end

--- Plain-text view (for fuzzel --dmenu).
function M.render_text(binds)
    local groups, order = grouped(binds)
    local out = {}
    for _, g in ipairs(order) do
        for _, e in ipairs(groups[g] or {}) do
            out[#out + 1] = ("%-12s %-28s %s"):format(g, e.keys, e.desc)
        end
    end
    return table.concat(out, "\n") .. "\n"
end

--- Markdown view (docs/SHORTCUTS.md).
function M.render_markdown(binds)
    local groups, order = grouped(binds)
    local out = {
        "# Kessel shortcuts",
        "",
        "<!-- GENERATED by scripts/gen-shortcuts.sh from .config/hypr/keybinds.lua — do not edit by hand. -->",
        "",
    }
    for _, g in ipairs(order) do
        if groups[g] then
            out[#out + 1] = "## " .. g
            out[#out + 1] = ""
            out[#out + 1] = "| Keys | Action |"
            out[#out + 1] = "| --- | --- |"
            for _, e in ipairs(groups[g]) do
                out[#out + 1] = ("| `%s` | %s |"):format(e.keys, e.desc)
            end
            out[#out + 1] = ""
        end
    end
    return table.concat(out, "\n")
end

local function write(path, content)
    local f, err = io.open(path, "w")
    if not f then print("[kessel] cannot write " .. path .. ": " .. tostring(err)); return end
    f:write(content)
    f:close()
end

function M.apply(registry)
    local seen, errors = {}, {}
    for _, e in ipairs(registry.binds) do
        if not e.doc then
            local k = normalize(e.keys)
            if seen[k] then
                errors[#errors + 1] = ("duplicate bind %s (%s / %s)"):format(e.keys, seen[k], e.desc)
            else
                seen[k] = e.desc
                local opts = { description = e.desc }
                for ok_, v in pairs(e.opts or {}) do opts[ok_] = v end
                local ok, err = pcall(function() hl.bind(e.keys, dispatcher(e), opts) end)
                if ok then
                    safety.bound[e.keys] = true
                else
                    errors[#errors + 1] = ("%s: %s"):format(e.keys, tostring(err))
                end
            end
        end
    end

    local runtime = os.getenv("XDG_RUNTIME_DIR")
    if runtime then write(runtime .. "/kessel-shortcuts.txt", M.render_text(registry.binds)) end
    local md = os.getenv("KESSEL_SHORTCUTS_MD")
    if md then write(md, M.render_markdown(registry.binds)) end

    if #errors > 0 then error(table.concat(errors, "; "), 0) end
end

return M
